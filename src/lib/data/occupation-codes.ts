export function getOccupationLabel(code: number): string {
  // Try exact match
  if (OCCUPATION_GROUP_MAP[code]) {
    return OCCUPATION_GROUP_MAP[code];
  }

  // Find closest lower code (occupation groups)
  const codes = Object.keys(OCCUPATION_GROUP_MAP)
    .map(Number)
    .sort((a, b) => a - b);
  let bestMatch = codes[0];
  for (const c of codes) {
    if (c <= code) bestMatch = c;
    else break;
  }
  return OCCUPATION_GROUP_MAP[bestMatch] ?? "Worker";
}
