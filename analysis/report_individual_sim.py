"""Results note for the individual-simulation study, written from its artifact.

Every number comes from paper/artifacts/individual-sim.json (written by
analysis/analyze_individual_sim.py); nothing here is typed by hand.

Output: paper/individual-sim-results.md

Run: python3 analysis/report_individual_sim.py
"""

import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "paper", "artifacts", "individual-sim.json")
OUT = os.path.join(ROOT, "paper", "individual-sim-results.md")
MODELS = ["gpt-6-luna", "gpt-6.1-sol"]


def pts(v):
    return "—" if v is None else f"{100 * v:.1f}"


def signed(v):
    return f"{'+' if v > 0 else ''}{100 * v:.1f}"


def ci(d):
    if not d:
        return "—"
    return f"{signed(d['diff'])} [{signed(d['lo'])}, {signed(d['hi'])}]"


def main(src=SRC, out=OUT):
    a = json.load(open(src))
    if "MOCK_DATA" in a:
        sys.exit("refusing to report a mock-mode artifact")
    m = a["models"]
    lines = [
        "# Individual-simulation study (October 2026): results",
        "",
        "Generated by `analysis/report_individual_sim.py` from `paper/artifacts/individual-sim.json`;",
        "do not edit by hand. Registration: `paper/pap-individual-sim-2026-10.md`",
        "(tag `pap-individual-sim-2026-10`), whose post-run notes record any deviation.",
        "Errors are absolute errors of the designated answer share, in percentage points;",
        "subgroup error pools all reported bins. Intervals are paired item-resampling",
        "bootstrap 95% CIs, conditional on the released pool, the single cells and direct",
        "runs and the census replies. Positive differences mean the individual arm is less accurate.",
        "",
        "## Accuracy on all 63 items",
        "",
        "| Model · arm | Topline | Subgroup | Cells topline | Cells subgroup | Direct topline | Direct subgroup |",
        "|---|---|---|---|---|---|---|",
    ]
    for model in MODELS:
        cells = (m[model].get("cells") or {}).get("all63") or {}
        direct = (m[model].get("naive") or {}).get("all63") or {}
        for arm, label in (("persona-prob-pool", "released pool"), ("persona-prob-fresh", "new pool per item")):
            c = ((m[model].get(arm) or {}).get("census") or {}).get("all63")
            if not c:
                continue
            lines.append(
                f"| {model} · {label} | {pts(c['toplineMAE'])} | {pts(c['subgroupMAE'])} | "
                f"{pts(cells.get('toplineMAE'))} | {pts(cells.get('subgroupMAE'))} | "
                f"{pts(direct.get('toplineMAE'))} | {pts(direct.get('subgroupMAE'))} |"
            )
    lines += ["", "## Registered comparisons", "",
              "| Comparison | Items | Topline difference | Subgroup difference |", "|---|---|---|---|"]

    def row(name, d):
        if d:
            lines.append(f"| {name} | {d['items']} | {ci(d['topline'])} | {ci(d['subgroup'])} |")

    for model in MODELS:
        for s in ("all63", "other43"):
            row(f"Q1 {model}: individual minus cells ({s})", (a["Q1_individualVsCells"].get(model) or {}).get(s))
        for s in ("all63", "other43"):
            row(f"Q2 {model}: individual minus direct ({s})", (a["Q2_individualVsDirect"].get(model) or {}).get(s))
    row("Q4 gpt-6-luna: new pools minus released pool", a["Q4_freshPools"]["vsPool"])
    row("Q4 gpt-6-luna: new pools minus cells", a["Q4_freshPools"]["vsCells"])
    row("Q5 gpt-6-luna minus gpt-6.1-sol (released pool)", a["Q5_lunaVsSol"])
    for model in MODELS:
        d4 = a["D4_subset20"].get(model) or {}
        row(f"D4 {model}: 1,200 people minus amendment 2's 150 (20 items)", d4.get("vsPersonaProb150"))
        row(f"D4 {model}: individual probabilities minus one answer each (20 items)", d4.get("vsPersona"))

    lines += ["", "## People per item (Q3)", "",
              "Expected error when a run asks K people of the released pool; subgroup error weights",
              "each bin by the share of runs that show it.", "",
              "| Model | K | Topline | Subgroup | Subgroups shown | vs cells, topline | vs cells, subgroup |",
              "|---|---|---|---|---|---|---|"]
    for model in MODELS:
        byk = (m[model].get("persona-prob-pool") or {}).get("byK") or {}
        census_bins = (byk.get("1200") or {}).get("all63", {}).get("bins") or 0
        for k in ("150", "300", "600", "1200"):
            s = (byk.get(k) or {}).get("all63")
            if not s:
                continue
            shown = f"{100 * s['expectedBinsShown'] / census_bins:.0f}%" if census_bins else "—"
            q3 = a["Q3_byKVsCells"].get(model, {}).get(k)
            lines.append(f"| {model} | {int(k):,} | {pts(s['toplineMAE'])} | {pts(s['subgroupMAE'])} | {shown} | "
                         f"{ci(q3['topline']) if q3 else '—'} | {ci(q3['subgroup']) if q3 else '—'} |")

    rule = a["productRule"]
    lines += ["", "## Registered product rules", ""]
    lines.append(f"- People per run (rule 1): K* = {rule['people']:,}." if rule["people"] else
                 "- People per run (rule 1): not computed (gpt-6-luna's run did not cover all 63 items).")
    for k, d in sorted(rule["addedErrorVsCensusByK"].items(), key=lambda kv: int(kv[0])):
        lines.append(f"  - K = {int(k):,} adds {signed(d['topline']['diff'])} topline and "
                     f"{signed(d['subgroup']['diff'])} subgroup points to the census (tolerance {pts(rule['kTolerance'])}).")
    for model, g in rule["gate"]["byModel"].items():
        gap = g["gapToCells"]
        detail = (f"{signed(gap['topline'])} topline, {signed(gap['subgroup'])} subgroup points behind cells"
                  if gap else "not scored")
        lines.append(f"- Gate (rule 2), {model}: {'passes' if g['passes'] else 'fails'} ({detail}; margin "
                     f"{pts(rule['gate']['margin'])}; all items covered: {'yes' if g['complete'] else 'no'}"
                     f"{'; flagged: ' + ', '.join(g['flaggedItems']) if g['flaggedItems'] else ''}).")
    lines.append(f"- Default (rule 3): {'eligible to be proposed' if rule['defaultEligible'] else 'not eligible; cells stay the default'}.")
    bench = a.get("individualBenchmark") or {}
    for model, b in bench.items():
        lines.append(f"- Displayed accuracy (rule 4), {model}: {pts(b['topline'])} topline, {pts(b['subgroup'])} subgroup "
                     f"points with {b['people']:,} people; {100 * b['shareOfSubgroupsShown']:.0f}% of subgroups shown.")
    if not bench:
        lines.append("- Displayed accuracy (rule 4): no model passed the gate, so the mode has no displayed accuracy.")

    lines += ["", "## Descriptive checks", ""]
    for model, r in (a.get("D1_testRetest") or {}).items():
        r_txt = f"{r['meanWithinItemPearson']:.2f}" if r["meanWithinItemPearson"] is not None else "—"
        lines.append(f"- D1 test-retest, {model}: within-item correlation {r_txt} over {r['itemsWithPearson']} items "
                     f"({r['pairs']:,} person pairs); mean absolute difference {pts(r['meanWithinItemAbsDiff'])} points, "
                     f"against a within-item SD of first answers of {pts(r['meanWithinItemSD'])}.")
    for model in MODELS:
        for arm in ("persona-prob-pool", "persona-prob-fresh"):
            e = m[model].get(arm)
            if not e:
                continue
            se = ", ".join(f"K = {int(k):,}: {pts(v['meanPersonSamplingSE'])} ({v['binsWithSE']} bins)"
                           for k, v in sorted(e["byK"].items(), key=lambda kv: int(kv[0])))
            lines.append(f"- D2 sampling error, {model} {arm}: mean person-sampling SE of bin estimates {se}; "
                         f"census bins as samples of the population {pts(e['meanFrameSE'])}.")
            c = e["cost"]
            lines.append(f"- D3 {model} {arm}: {c['calls']:,} answered calls, {c['failedCalls']} failed, "
                         f"{c['truncatedLines']} cut-off log lines; failure rate of elicitations "
                         f"{100 * (e['census']['all63']['failureRate'] or 0):.2f}%; flagged items: "
                         f"{', '.join(e['flaggedItems']) or 'none'}; cost ${c['usd']:.2f}.")
    for key, d in (a.get("D5_postStratified") or {}).items():
        lines.append(f"- D5 composition, {key.replace('|', ' ')}: post-stratified topline {pts(d['all63']['toplineMAE'])}, "
                     f"subgroup {pts(d['all63']['subgroupMAE'])}; difference from the unweighted census "
                     f"{ci(d['vsCensus']['topline'])} topline, {ci(d['vsCensus']['subgroup'])} subgroup.")
    ex = a.get("exploratory") or {}
    if ex:
        lines += ["", "## Exploratory (not registered)", "", ex["note"], ""]
        e1 = ex.get("E1_satjobAbstentionsAsOutOfUniverse")
        if e1:
            for key, v in e1["abstentions"].items():
                lines.append(f"- E1 {key.replace('|', ' ')}: {v['unparsed']} unparsed gss_satjob replies, "
                             f"{v['unparsedWithNoEarnings']} of them from the {v['peopleWithNoEarnings']} people with no earnings.")
            r = e1["productRule"]
            lines.append(f"- E1 with those abstentions exempted from flagging (the item's scores unchanged): K* = {r['people']:,}." if r["people"] else
                         "- E1 with those abstentions exempted from flagging: K* not computed.")
            for model, g in r["gate"]["byModel"].items():
                gap = g["gapToCells"]
                lines.append(f"  - {model}: gate {'passes' if g['passes'] else 'fails'}"
                             + (f" ({signed(gap['topline'])} topline, {signed(gap['subgroup'])} subgroup points behind cells)." if gap else "."))
        for model, e2 in (ex.get("E2_signedToplineError") or {}).items():
            parts = ", ".join(f"{k} ({v['items']} items): individual {signed(v['individual'])}, cells {signed(v['cells'])}"
                              for k, v in e2["meanSignedToplineErrorByValence"].items())
            lines.append(f"- E2 mean signed topline error by valence, {model}: {parts}.")
            gaps = "; ".join(f"{g['itemId']} {signed(g['individualSigned'])} vs {signed(g['cellsSigned'])}"
                             for g in e2["largestGapsToCells"][:5])
            lines.append(f"  - Largest gaps to cells (individual vs cells, signed): {gaps}.")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(out, ROOT)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
